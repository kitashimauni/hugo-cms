import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

export default function outputAssetPlugin(eleventyConfig) {
  eleventyConfig.addShortcode("generateOutputAsset", () => {
    const outputPath = path.resolve("public", "img", "generated.txt");
    mkdirSync(path.dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, "generated by fixture\n");
    return "";
  });
}
